/** 生成 blank_priority：按字母（去空格、转小写）标注，0 = 不挖空，1 = 优先挖空。
 *  规则：冠词/短功能词(a, an, the, of, to, in, on, at, for)所含字母 → 0；
 *       短语首字母与末字母 → 0（作为锚点）；其余字母 → 1。 */
function bp(phrase) {
  const ARTICLES = new Set(['a', 'an', 'the', 'of', 'to', 'in', 'on', 'at', 'for']);
  const words = phrase.toLowerCase().split(/\s+/).filter(Boolean);
  const letters = [];
  for (const w of words) {
    const isArticle = ARTICLES.has(w);
    for (const ch of w) {
      if (!/[a-z]/.test(ch)) continue;
      letters.push(isArticle ? 0 : 1);
    }
  }
  if (letters.length > 2) {
    letters[0] = 0;
    letters[letters.length - 1] = 0;
  }
  return letters;
}

